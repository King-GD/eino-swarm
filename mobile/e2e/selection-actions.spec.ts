test("worker selections can be read, translated and added to the parent draft", async ({ page }, info) => {
  await page.addInitScript(() => localStorage.setItem("zwai.phone.locale", "zh"))
  await page.goto("/?mock=1&tick=150&history=streamed-agents&speech=local&speech_delay=800")
  await page.getByRole("button", { name: /子 Agent.*3/ }).tap()
  await page.getByTestId("agent-roster").getByRole("button", { name: /worker-1/ }).tap()
  const transcript = page.getByTestId("transcript")
  const source = transcript.getByText("Worker evidence", { exact: true })
  await expect(source).toBeInViewport()
  await source.evaluate((element) => {
    const range = document.createRange()
    range.selectNodeContents(element)
    window.getSelection()?.removeAllRanges()
    window.getSelection()?.addRange(range)
    document.dispatchEvent(new Event("selectionchange"))
  })

  const toolbar = page.getByRole("toolbar", { name: "选中文字操作" })
  await expect(toolbar).toBeInViewport()
  await toolbar.getByRole("button", { name: "朗读", exact: true }).tap()
  await expect(toolbar.getByRole("button", { name: "停止朗读" })).toHaveAttribute("data-playback-state", "playing")
  await toolbar.getByRole("button", { name: "停止朗读" }).tap()
  await toolbar.getByRole("button", { name: "翻译" }).tap()
  await expect(page.getByRole("region", { name: "译文" })).toContainText("离线选区翻译。")
  await expect(source).toBeInViewport()
  await expect(page.getByTestId("quote-draft")).toHaveCount(0)
  await page.screenshot({ path: info.outputPath("worker-selection-translation.png") })

  await toolbar.getByRole("button", { name: "加入对话" }).tap()
  await expect(toolbar).toHaveCount(0)
  await expect(transcript).not.toContainText("Worker evidence")
  await expect(page.getByRole("button", { name: /子 Agent.*3/ })).toBeVisible()
  await expect(page.getByLabel("消息", { exact: true })).toHaveValue("")
  await expect(page.getByTestId("quote-draft")).toHaveValue("Worker evidence")
})
